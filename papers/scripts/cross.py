#!/usr/bin/env python3
"""Table 2 and the data of Figure 3 of index.html: Mem0 and Zep with one model writing the store and another reading it.

    ../.venv/bin/python scripts/cross.py [results dir]

Where one model writes and reads, the cell is Table 1's (data/conv26_cumulative.json). Every other cell reuses
the writer's store and its saved retrievals and changes only the model that answers
(src/methods/<mem0|zep>/reanswer.py, results/<mem0|zep>/<writer>-<reader>/). A complete run is copied into
data/conv26_cross.json; a missing or unfinished one leaves the file as it was, and a cell never run is drawn
as not run yet. Both are written into index.html between their markers.
"""

import json
import sys
from pathlib import Path

from conv26 import CATEGORIES, MODELS, sig

PAPER = Path(__file__).resolve().parents[1]
DATA = PAPER / "data/conv26_cross.json"
METHODS = {"mem0": "Mem0", "zep": "Zep"}
PAIRS = [(m, w, r) for m in METHODS for w in MODELS for r in MODELS if w != r]
SPLIT = ' class="split"'  # the rule between the Mem0 and Zep columns


def copy(results):
    """Complete cross runs from results/ into data/conv26_cross.json."""
    data = json.loads(DATA.read_text()) if DATA.exists() else {"cells": []}
    cells = {(c["method"], c["writer"], c["reader"]): c for c in data["cells"]}
    for m, w, r in PAIRS:
        path = results / m / f"{w}-{r}" / "summary.json"
        if not path.exists():
            continue
        s = json.loads(path.read_text())
        if s["status"] != "complete":
            continue
        # The reader answers at its own effort, as in Table 1.
        if (s["settings"]["reasoning_effort"], s["model"]) != (MODELS[r][1] or "none", s["settings"]["roles"]["answer"]["model"]):
            raise ValueError(f"{path}: reader effort or model differs from Table 1's {r}")
        cells[(m, w, r)] = {
            "method": m, "writer": w, "reader": r, "run": f"results/{m}/{w}-{r}",
            "store": s["settings"]["store"].split("results/")[-1], "reasoning_effort": s["settings"]["reasoning_effort"],
            "questions": [{"id": q["id"], "category": q["category"], "correct": bool(q["correct"]), "cost_usd": q["query_cost_usd"]}
                          for q in s["rows"]],
        }
    data = {"source": "results/<mem0|zep>/<writer>-<reader>/summary.json, written by src/methods/<method>/reanswer.py "
                      "from the writer's store; questions as in conv26_cumulative.json.",
            "cells": [cells[k] for k in PAIRS if k in cells]}
    DATA.write_text(json.dumps(data, indent=1) + "\n")
    return cells


def grid(cells):
    """Every writer-reader cell of both methods: Table 1's diagonal, the copied runs, and the rest not run yet."""
    table1 = {(c["method"], c["model"]): c for c in json.loads((PAPER / "data/conv26_cumulative.json").read_text())["cells"]}
    out = []
    for m, name in METHODS.items():
        for w in MODELS:
            build = table1[(name, w)]["build_usd"]
            for r in MODELS:
                c = table1[(name, w)] if w == r else cells.get((m, w, r))
                cell = {"method": m, "writer": w, "reader": r, "build": build}
                if c:
                    qs = c["questions"]
                    cell.update(correct=sum(q["correct"] for q in qs), n=len(qs),
                                byCategory=[sum(q["correct"] for q in qs if q["category"] == k) for k in CATEGORIES],
                                perQ=float(sig(sum(q["cost_usd"] for q in qs) / len(qs))))
                out.append(cell)
    return out


def table(cells):
    at = {(c["method"], c["writer"], c["reader"]): c for c in cells}
    # Column names wrap at spaces only: GPT-4o-mini keeps its hyphens.
    head = "".join(f'<th{SPLIT if i == 0 and m != "mem0" else ""}>{MODELS[r][0].replace("-", chr(0x2011))}</th>'
                   for m in METHODS for i, r in enumerate(MODELS))
    lines = ["<table>", "<thead>",
             "<tr><th></th>" + "".join(f'<th colspan="{len(MODELS)}"{SPLIT if m != "mem0" else ""}>{name}, read by</th>'
                                       for m, name in METHODS.items()) + "</tr>",
             f"<tr><th>Written by</th>{head}</tr>", "</thead>", "<tbody>"]
    for w in MODELS:
        tds = []
        for m in METHODS:
            for i, r in enumerate(MODELS):
                c = at[(m, w, r)]
                cls = [k for k, on in (("split", i == 0 and m != "mem0"), ("diag", w == r), ("pending", "correct" not in c)) if on]
                attr = f' class="{" ".join(cls)}"' if cls else ""
                tds.append(f"<td{attr}>{int(100 * c['correct'] / c['n'] + 0.5) if 'correct' in c else '…'}</td>")
        lines.append(f"<tr><td>{MODELS[w][0]}</td>{''.join(tds)}</tr>")
    return "\n".join(lines + ["</tbody>", "</table>"])


def replace(text, name, body):
    begin, end = f"<!-- {name}: generated by scripts/cross.py -->", f"<!-- end {name} -->"
    head, rest = text.split(begin)
    _, tail = rest.split(end)
    return head + begin + "\n" + body + "\n" + end + tail


def main():
    results = Path(sys.argv[1]) if len(sys.argv) > 1 else PAPER.parent / "results"
    cells = grid(copy(results))
    data = {"n": cells[0]["n"], "models": {k: v[0] for k, v in MODELS.items()}, "methods": METHODS,
            "categories": list(CATEGORIES.values()), "cells": cells}
    page = PAPER / "index.html"
    text = replace(page.read_text(), "cross table", table(cells))
    script = '<script type="application/json" id="cross-data">' + json.dumps(data, separators=(",", ":")) + "</script>"
    page.write_text(replace(text, "cross data", script))
    for m in METHODS:
        print(METHODS[m])
        for w in MODELS:
            row = [str(c.get("correct", "…")) for c in cells if c["method"] == m and c["writer"] == w]
            print(f"  written by {MODELS[w][0]:<16} read by {', '.join(MODELS)}: {' '.join(f'{v:>4}' for v in row)}")


if __name__ == "__main__":
    main()
